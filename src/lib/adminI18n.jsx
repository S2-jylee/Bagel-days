const AdminLangContext = createContext(null);

export function AdminLangProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("admin_lang") || "en");

  useEffect(() => {
    localStorage.setItem("admin_lang", lang);
  }, [lang]);

  function t(key, ...args) {
    const entry = STRINGS[lang]?.[key] ?? STRINGS.en[key];
    return typeof entry === "function" ? entry(...args) : entry ?? key;
  }

  return <AdminLangContext.Provider value={{ lang, setLang, t }}>{children}</AdminLangContext.Provider>;
}

export function useAdminLang() {
  const ctx = useContext(AdminLangContext);
  if (!ctx) throw new Error("useAdminLang must be used within AdminLangProvider");
  return ctx;
}
